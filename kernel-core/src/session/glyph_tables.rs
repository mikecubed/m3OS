pub static GLYPH_TABLE_BOX_DRAWING: [Glyph; BOX_DRAWING_COUNT] = build_box_drawing_glyph_table();

/// Centred-dot fallback glyph, used whenever
/// [`resolve_glyph`] is called with a codepoint outside the covered
/// ranges (and outside the control-character ranges, which render
/// blank).
///
/// Phase 69b Track E — single fallback for every "we don't have a
/// glyph yet" case. Renderers can compare a returned `&Glyph` against
/// this value to special-case the visible-placeholder behaviour.
pub static FALLBACK_DOT_GLYPH: Glyph = Glyph {
    width: CELL_WIDTH,
    height: CELL_HEIGHT,
    bitmap: &FALLBACK_DOT_BITMAP,
};

/// Blank glyph used for control characters (U+0000..=U+001F,
/// U+0080..=U+009F, U+007F) — keeps a typed value the renderer can
/// hand back when the caller asks for a control codepoint.
pub static BLANK_GLYPH: Glyph = Glyph {
    width: CELL_WIDTH,
    height: CELL_HEIGHT,
    bitmap: &BLANK,
};

const fn build_latin1_glyph_table() -> [Glyph; LATIN1_COUNT] {
    let mut out: [Glyph; LATIN1_COUNT] = [Glyph {
        width: CELL_WIDTH,
        height: CELL_HEIGHT,
        bitmap: &BLANK,
    }; LATIN1_COUNT];
    let mut i: usize = 0;
    while i < LATIN1_COUNT {
        out[i] = Glyph {
            width: CELL_WIDTH,
            height: CELL_HEIGHT,
            // Reference into the static `LATIN1_BITMAPS` slot. Each
            // sub-array is itself a `'static` slice because the
            // owning array is `static`.
            bitmap: latin1_bitmap_slice(i),
        };
        i += 1;
    }
    out
}

const fn latin1_bitmap_slice(index: usize) -> &'static [u8] {
    // Build a static reference into the bitmaps array by treating
    // each row as a slice. The const-context restriction that
    // forbids index-into-array via `&LATIN1_BITMAPS[i]` is satisfied
    // by `&LATIN1_BITMAPS[i][..]` — both forms are accepted at
    // compile time for `static` arrays of `Copy` types.
    let slot: &[u8; BYTES_PER_GLYPH] = &LATIN1_BITMAPS[index];
    slot
}

const fn build_box_drawing_glyph_table() -> [Glyph; BOX_DRAWING_COUNT] {
    let mut out: [Glyph; BOX_DRAWING_COUNT] = [Glyph {
        width: CELL_WIDTH,
        height: CELL_HEIGHT,
        bitmap: &BLANK,
    }; BOX_DRAWING_COUNT];
    let mut i: usize = 0;
    while i < BOX_DRAWING_COUNT {
        out[i] = Glyph {
            width: CELL_WIDTH,
            height: CELL_HEIGHT,
            bitmap: box_drawing_bitmap_slice(i),
        };
        i += 1;
    }
    out
}

const fn box_drawing_bitmap_slice(index: usize) -> &'static [u8] {
    let slot: &[u8; BYTES_PER_GLYPH] = &BOX_DRAWING_BITMAPS[index];
    slot
}

/// Phase 69b Track E — single glyph resolver.
///
/// Dispatches by codepoint:
///
/// - **U+0020..=U+007E** → ASCII bitmap table
///   ([`crate::session::font_data::GLYPH_BITMAPS`]).
/// - **U+0080..=U+00FF** → [`GLYPH_TABLE_LATIN1`].
/// - **U+2500..=U+257F** → [`GLYPH_TABLE_BOX_DRAWING`].
/// - **U+0000..=U+001F**, **U+007F**, **U+0080..=U+009F** →
///   [`BLANK_GLYPH`] (control characters render to a blank cell;
///   `0x7F` DEL is covered by the ASCII table already but kept here
///   for symmetry).
/// - Everything else → [`FALLBACK_DOT_GLYPH`].
///
/// The returned reference always has a `'static` lifetime so renderers
/// can hold onto it for the duration of a paint pass without copying.
pub fn resolve_glyph(codepoint: u32) -> &'static Glyph {
    // Control characters render blank — same behaviour every terminal
    // applies to invisible control bytes.
    if codepoint <= 0x1F
        || codepoint == 0x7F
        || (0x80..=0x9F).contains(&codepoint)
        || codepoint == 0xA0
    {
        return &BLANK_GLYPH;
    }
    if (ASCII_FIRST..=ASCII_LAST).contains(&codepoint) {
        let idx = (codepoint - ASCII_FIRST) as usize;
        return &GLYPH_BITMAPS[idx];
    }
    if (LATIN1_FIRST..=LATIN1_LAST).contains(&codepoint) {
        let idx = (codepoint - LATIN1_FIRST) as usize;
        return &GLYPH_TABLE_LATIN1[idx];
    }
    if (BOX_DRAWING_FIRST..=BOX_DRAWING_LAST).contains(&codepoint) {
        let idx = (codepoint - BOX_DRAWING_FIRST) as usize;
        return &GLYPH_TABLE_BOX_DRAWING[idx];
    }
    &FALLBACK_DOT_GLYPH
}

