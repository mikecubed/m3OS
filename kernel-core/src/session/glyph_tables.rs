/// Render an `EdgeSpec` to a 16-byte 8×16 bitmap.
const fn render_edge_spec(spec: EdgeSpec) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    let north = spec[0];
    let east = spec[1];
    let south = spec[2];
    let west = spec[3];

    // North stroke — column at centre, rows 0..CENTER_ROW.
    let mut r: usize = 0;
    while r < CENTER_ROW {
        out[r] |= column_mask(north);
        r += 1;
    }
    // South stroke — rows CENTER_ROW..BYTES_PER_GLYPH.
    let mut r: usize = CENTER_ROW;
    while r < BYTES_PER_GLYPH {
        out[r] |= column_mask(south);
        r += 1;
    }
    // East / West strokes — rows in a horizontal band around centre.
    // Double-line horizontals use rows 6/7 + 8/9.
    let west_mask_high = row_mask_left(west, true);
    let west_mask_low = row_mask_left(west, false);
    let east_mask_high = row_mask_right(east, true);
    let east_mask_low = row_mask_right(east, false);

    out[CENTER_ROW - 1] |= west_mask_high | east_mask_high;
    out[CENTER_ROW] |= west_mask_low | east_mask_low;

    // For "Double" strokes, paint a second parallel line two rows
    // away so the result reads as a double line.
    if matches!(north, EdgeKind::Double) {
        // North-bound double rail: paint another column 2 pixels away.
        let mut r: usize = 0;
        while r < CENTER_ROW {
            out[r] |= double_north_extra();
            r += 1;
        }
    }
    if matches!(south, EdgeKind::Double) {
        let mut r: usize = CENTER_ROW;
        while r < BYTES_PER_GLYPH {
            out[r] |= double_south_extra();
            r += 1;
        }
    }
    if matches!(east, EdgeKind::Double) {
        out[CENTER_ROW - 2] |= east_double_extra();
        out[CENTER_ROW + 1] |= east_double_extra();
    }
    if matches!(west, EdgeKind::Double) {
        out[CENTER_ROW - 2] |= west_double_extra();
        out[CENTER_ROW + 1] |= west_double_extra();
    }

    out
}

const fn column_mask(kind: EdgeKind) -> u8 {
    match kind {
        EdgeKind::None => 0,
        EdgeKind::Light => CENTER_COL_BIT,
        EdgeKind::Heavy => MASK_CENTER,
        EdgeKind::Double => MASK_DOUBLE_RAILS,
    }
}

const fn row_mask_left(kind: EdgeKind, _high_row: bool) -> u8 {
    match kind {
        EdgeKind::None => 0,
        EdgeKind::Light | EdgeKind::Double => 0xF0, // four leftmost pixels
        EdgeKind::Heavy => 0xF0,
    }
}

const fn row_mask_right(kind: EdgeKind, _high_row: bool) -> u8 {
    match kind {
        EdgeKind::None => 0,
        EdgeKind::Light | EdgeKind::Double => 0x1F, // five rightmost pixels
        EdgeKind::Heavy => 0x1F,
    }
}

const fn double_north_extra() -> u8 {
    // Second rail at column 5.
    0x04
}

const fn double_south_extra() -> u8 {
    0x04
}

const fn east_double_extra() -> u8 {
    0x1F
}

const fn west_double_extra() -> u8 {
    0xF0
}

/// Special-case box-drawing codepoints not covered by `edge_spec_for`.
const fn special_box_bitmap_for(codepoint: u32) -> [u8; BYTES_PER_GLYPH] {
    match codepoint {
        // Light arc corners: visually close to the matching right-
        // angle corner. Approximated as the right-angle corner.
        0x256D => render_edge_spec([
            EdgeKind::None,
            EdgeKind::Light,
            EdgeKind::Light,
            EdgeKind::None,
        ]),
        0x256E => render_edge_spec([
            EdgeKind::None,
            EdgeKind::None,
            EdgeKind::Light,
            EdgeKind::Light,
        ]),
        0x256F => render_edge_spec([
            EdgeKind::Light,
            EdgeKind::None,
            EdgeKind::None,
            EdgeKind::Light,
        ]),
        0x2570 => render_edge_spec([
            EdgeKind::Light,
            EdgeKind::Light,
            EdgeKind::None,
            EdgeKind::None,
        ]),

        // Diagonals.
        0x2571 => [
            // Forward slash from bottom-left to top-right (/)
            0x01, 0x03, 0x02, 0x06, 0x04, 0x0C, 0x08, 0x18, 0x10, 0x30, 0x20, 0x60, 0x40, 0xC0,
            0x80, 0x00,
        ],
        0x2572 => [
            // Back slash from top-left to bottom-right (\)
            0x80, 0xC0, 0x40, 0x60, 0x20, 0x30, 0x10, 0x18, 0x08, 0x0C, 0x04, 0x06, 0x02, 0x03,
            0x01, 0x00,
        ],
        0x2573 => [
            // Cross: both diagonals OR'd together.
            0x81, 0xC3, 0x42, 0x66, 0x24, 0x3C, 0x18, 0x18, 0x18, 0x3C, 0x24, 0x66, 0x42, 0xC3,
            0x81, 0x00,
        ],

        // Half-line endpoints (U+2574..U+257B).
        0x2574 => half_left(EdgeKind::Light),
        0x2575 => half_top(EdgeKind::Light),
        0x2576 => half_right(EdgeKind::Light),
        0x2577 => half_bottom(EdgeKind::Light),
        0x2578 => half_left(EdgeKind::Heavy),
        0x2579 => half_top(EdgeKind::Heavy),
        0x257A => half_right(EdgeKind::Heavy),
        0x257B => half_bottom(EdgeKind::Heavy),

        // Mixed half-strokes: U+257C..U+257F join one light edge to a
        // heavy edge through the centre. We render each as the
        // matching full horizontal/vertical and accept the
        // visual approximation.
        0x257C => render_edge_spec([
            EdgeKind::None,
            EdgeKind::Heavy,
            EdgeKind::None,
            EdgeKind::Light,
        ]),
        0x257D => render_edge_spec([
            EdgeKind::Light,
            EdgeKind::None,
            EdgeKind::Heavy,
            EdgeKind::None,
        ]),
        0x257E => render_edge_spec([
            EdgeKind::None,
            EdgeKind::Light,
            EdgeKind::None,
            EdgeKind::Heavy,
        ]),
        0x257F => render_edge_spec([
            EdgeKind::Heavy,
            EdgeKind::None,
            EdgeKind::Light,
            EdgeKind::None,
        ]),

        _ => fallback_dot_bitmap(),
    }
}

const fn half_left(kind: EdgeKind) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    let mask = row_mask_left(kind, true);
    out[CENTER_ROW - 1] |= mask;
    out[CENTER_ROW] |= mask;
    out
}

const fn half_right(kind: EdgeKind) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    let mask = row_mask_right(kind, true);
    out[CENTER_ROW - 1] |= mask;
    out[CENTER_ROW] |= mask;
    out
}

const fn half_top(kind: EdgeKind) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    let mask = column_mask(kind);
    let mut r: usize = 0;
    while r < CENTER_ROW {
        out[r] |= mask;
        r += 1;
    }
    out
}

const fn half_bottom(kind: EdgeKind) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    let mask = column_mask(kind);
    let mut r: usize = CENTER_ROW;
    while r < BYTES_PER_GLYPH {
        out[r] |= mask;
        r += 1;
    }
    out
}

const fn build_box_drawing_bitmaps() -> [[u8; BYTES_PER_GLYPH]; BOX_DRAWING_COUNT] {
    let mut out = [[0u8; BYTES_PER_GLYPH]; BOX_DRAWING_COUNT];
    let mut i: usize = 0;
    while i < BOX_DRAWING_COUNT {
        let codepoint = BOX_DRAWING_FIRST + i as u32;
        let bm = match edge_spec_for(codepoint) {
            Option::Some(spec) => render_edge_spec(spec),
            Option::None => special_box_bitmap_for(codepoint),
        };
        out[i] = bm;
        i += 1;
    }
    out
}

