/// Phase 69b Track F — East Asian Width accounting.
///
/// Returns `2` for codepoints in the canonical always-wide CJK /
/// halfwidth-fullwidth ranges, and `1` for everything else. Glyph
/// tables for these ranges are not present in Phase 69b (they remain
/// deferred); landing the accounting here keeps the cell grid honest
/// so future phases that ship the tables only need to extend the
/// resolver, not the screen state machine.
///
/// Returned widths:
///
/// - **U+2E80..=U+9FFF** — CJK Radicals through CJK Unified
///   Ideographs.
/// - **U+3000..=U+30FF** — CJK Symbols and Punctuation through
///   Katakana.
/// - **U+AC00..=U+D7AF** — Hangul Syllables.
/// - **U+F900..=U+FAFF** — CJK Compatibility Ideographs.
/// - **U+FE30..=U+FE4F** — CJK Compatibility Forms.
/// - **U+FF00..=U+FF60** — Halfwidth and Fullwidth Forms (fullwidth
///   half).
/// - **U+FFE0..=U+FFE6** — Fullwidth signs.
pub fn width_of(codepoint: u32) -> u8 {
    if (0x2E80..=0x9FFF).contains(&codepoint)
        || (0x3000..=0x30FF).contains(&codepoint)
        || (0xAC00..=0xD7AF).contains(&codepoint)
        || (0xF900..=0xFAFF).contains(&codepoint)
        || (0xFE30..=0xFE4F).contains(&codepoint)
        || (0xFF00..=0xFF60).contains(&codepoint)
        || (0xFFE0..=0xFFE6).contains(&codepoint)
    {
        2
    } else {
        1
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Phase 69b Track C — table has exactly 128 entries covering
    /// the Latin-1 supplement range.
    #[test]
    fn latin1_table_size_matches_block() {
        assert_eq!(GLYPH_TABLE_LATIN1.len(), 128);
        assert_eq!(LATIN1_LAST - LATIN1_FIRST + 1, 128);
    }

    /// Phase 69b Track C — C1 control range (U+0080..=U+009F) and
    /// NBSP (U+00A0) render as a blank cell.
    #[test]
    fn latin1_c1_control_range_is_blank() {
        for cp in 0x80u32..=0xA0 {
            let g = resolve_glyph(cp);
            assert!(
                g.bitmap.iter().all(|&b| b == 0),
                "codepoint {:#06x} must render blank",
                cp
            );
        }
    }

    /// Phase 69b Track C — representative accented letters return a
    /// non-blank bitmap.
    #[test]
    fn latin1_representative_letters_have_inked_pixels() {
        for &cp in &[0x00C7, 0x00DC, 0x00E9, 0x00F1, 0x00A9, 0x00B1] {
            let g = resolve_glyph(cp);
            assert!(
                g.bitmap.iter().any(|&b| b != 0),
                "codepoint {:#06x} must have inked pixels",
                cp
            );
        }
    }

    /// Phase 69b Track C — a representative subset's pixels match
    /// the expected base-letter + diacritic pattern. Specifically
    /// 'é' (U+00E9) must have a diacritic stamp in rows 0..=1 and
    /// the lower-case 'e' shape in the shifted-down body.
    #[test]
    fn latin1_e_acute_bitmap_has_diacritic_then_base() {
        let g = resolve_glyph(0x00E9);
        // Diacritic stamp is row 0 = 0x18, row 1 = 0x30 per the
        // Acute mapping in `with_diacritic`.
        assert_eq!(g.bitmap[0], 0x18, "acute mark row 0");
        assert_eq!(g.bitmap[1], 0x30, "acute mark row 1");
        // The base lowercase 'e' shifted down by 2 means base[5] is
        // at out[7]: base_lower_e()[5] == 0x7C.
        assert_eq!(g.bitmap[7], 0x7C, "shifted-down 'e' top edge");
    }

    /// Phase 69b Track D — table has exactly 128 entries covering
    /// the Unicode box-drawing block.
    #[test]
    fn box_drawing_table_size_matches_block() {
        assert_eq!(GLYPH_TABLE_BOX_DRAWING.len(), 128);
        assert_eq!(BOX_DRAWING_LAST - BOX_DRAWING_FIRST + 1, 128);
    }

    /// Phase 69b Track D — the four light corners have a stroke
    /// going to the right cell side and a stroke going down/up the
    /// cell.
    #[test]
    fn box_drawing_corners_have_two_strokes_each() {
        // U+250C ┌ — light down + light right.
        let g = resolve_glyph(0x250C);
        // Centre row (row 7, 0-indexed) carries the east stroke.
        assert!(
            g.bitmap[7] & 0x1F != 0,
            "east stroke missing for U+250C: {:02x}",
            g.bitmap[7]
        );
        // South stroke runs from centre row to bottom.
        let south_pixels: u32 = g.bitmap[CENTER_ROW..].iter().map(|b| *b as u32).sum();
        assert!(south_pixels > 0, "south stroke missing for U+250C");

        // U+2510 ┐ — west + south.
        let g = resolve_glyph(0x2510);
        assert!(g.bitmap[7] & 0xF0 != 0, "west stroke missing for U+2510");

        // U+2514 └ — north + east.
        let g = resolve_glyph(0x2514);
        let north_pixels: u32 = g.bitmap[..CENTER_ROW].iter().map(|b| *b as u32).sum();
        assert!(north_pixels > 0, "north stroke missing for U+2514");

        // U+2518 ┘ — north + west.
        let g = resolve_glyph(0x2518);
        let north_pixels: u32 = g.bitmap[..CENTER_ROW].iter().map(|b| *b as u32).sum();
        assert!(north_pixels > 0, "north stroke missing for U+2518");
    }

    /// Phase 69b Track D — the four T-junctions carry three strokes
    /// each.
    #[test]
    fn box_drawing_t_junctions_have_three_strokes() {
        // U+252C ┬ — east + south + west.
        let g = resolve_glyph(0x252C);
        assert!(g.bitmap[7] & 0x1F != 0, "east stroke missing for U+252C");
        assert!(g.bitmap[7] & 0xF0 != 0, "west stroke missing for U+252C");
        let south_pixels: u32 = g.bitmap[CENTER_ROW..].iter().map(|b| *b as u32).sum();
        assert!(south_pixels > 0, "south stroke missing for U+252C");
    }

    /// Phase 69b Track D — the plain horizontal U+2500 has a stroke
    /// across the centre row with no vertical ink.
    #[test]
    fn box_drawing_horizontal_is_just_centre_band() {
        let g = resolve_glyph(0x2500);
        // Centre row + adjacent row carry ink.
        assert!(g.bitmap[7] != 0 || g.bitmap[8] != 0);
        // Top and bottom thirds carry no ink.
        for r in 0..6 {
            assert_eq!(g.bitmap[r], 0, "row {r} must be blank for U+2500");
        }
        for r in 10..BYTES_PER_GLYPH {
            assert_eq!(g.bitmap[r], 0, "row {r} must be blank for U+2500");
        }
    }

    /// Phase 69b Track E — every range boundary returns the expected
    /// glyph type.
    #[test]
    fn resolver_dispatches_each_range_to_its_table() {
        // Below the printable ASCII range — control char → blank.
        assert!(resolve_glyph(0x00).bitmap.iter().all(|&b| b == 0));
        // ASCII boundary low.
        assert!(resolve_glyph(0x20).bitmap.iter().any(|&b| b == 0));
        // ASCII boundary high.
        assert!(core::ptr::eq(
            resolve_glyph(0x41).bitmap.as_ptr(),
            GLYPH_BITMAPS[(0x41 - ASCII_FIRST) as usize].bitmap.as_ptr()
        ));
        // Latin-1 boundary.
        let g = resolve_glyph(0xA1);
        let expected = &GLYPH_TABLE_LATIN1[0x21];
        assert!(core::ptr::eq(g.bitmap.as_ptr(), expected.bitmap.as_ptr()));
        // Box-drawing boundary.
        let g = resolve_glyph(0x2500);
        let expected = &GLYPH_TABLE_BOX_DRAWING[0];
        assert!(core::ptr::eq(g.bitmap.as_ptr(), expected.bitmap.as_ptr()));
        // CJK codepoint → fallback dot (no glyph table for CJK in
        // Phase 69b).
        let g = resolve_glyph(0x4E2D);
        assert!(core::ptr::eq(
            g.bitmap.as_ptr(),
            FALLBACK_DOT_GLYPH.bitmap.as_ptr()
        ));
    }

    /// Phase 69b Track F — every range boundary returns width 2.
    #[test]
    fn width_of_canonical_cjk_ranges_returns_two() {
        let two = &[
            0x2E80u32, 0x9FFF, 0x3000, 0x30FF, 0xAC00, 0xD7AF, 0xF900, 0xFAFF, 0xFE30, 0xFE4F,
            0xFF00, 0xFF60, 0xFFE0, 0xFFE6,
        ];
        for &cp in two {
            assert_eq!(width_of(cp), 2, "codepoint {:#06x} must be width 2", cp);
        }
    }

    /// Phase 69b Track F — codepoints outside the canonical wide
    /// ranges return width 1.
    #[test]
    fn width_of_non_cjk_returns_one() {
        let one = &[
            0x0041u32, 0x00E9, 0x2500, 0x2E7F, // one below the CJK Radicals start
            0xA000, // one above Hangul Syllables end
            0xFB00, // boundary above CJK Compatibility Forms
        ];
        for &cp in one {
            assert_eq!(width_of(cp), 1, "codepoint {:#06x} must be width 1", cp);
        }
    }

    /// Phase 69b Track E — the fallback dot has exactly four inked
    /// pixels (a 2×2 block at the cell centre) — sanity-check the
    /// shape stays small.
    #[test]
    fn fallback_dot_is_a_two_by_two_block() {
        assert_eq!(FALLBACK_DOT_GLYPH.bitmap[7], 0x18);
        assert_eq!(FALLBACK_DOT_GLYPH.bitmap[8], 0x18);
        // All other rows are blank.
        for (r, &b) in FALLBACK_DOT_GLYPH.bitmap.iter().enumerate() {
            if r != 7 && r != 8 {
                assert_eq!(b, 0, "row {r} of fallback dot must be blank");
            }
        }
    }
}
