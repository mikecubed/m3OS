//! Phase 69b Tracks C/D/E — Latin-1 supplement and Unicode box-drawing
//! bitmap glyph tables, plus the unified [`resolve_glyph`] accessor.
//!
//! ## Coverage
//!
//! - **U+0020..=U+007F** — ASCII printables. Resolved against the
//!   existing [`crate::session::font_data::GLYPH_BITMAPS`] table.
//! - **U+0080..=U+00FF** — Latin-1 supplement. Covered by the
//!   [`LATIN1_GLYPHS`] table below. C1 control characters
//!   (U+0080..=U+009F) plus U+00A0 (NBSP) render as a blank cell —
//!   exactly the "no inked pixels" behaviour every terminal applies
//!   to control codes.
//! - **U+2500..=U+257F** — Unicode box-drawing block. Covered by the
//!   [`BOX_DRAWING_GLYPHS`] table.
//! - **Everything else** — the centred-dot fallback glyph
//!   [`FALLBACK_DOT_GLYPH`], matching the Phase 69b design's "single
//!   replacement glyph" rule.
//!
//! ## Provenance
//!
//! - ASCII glyphs (out of scope here, see `font_data.rs`) come from
//!   the public-domain IBM VGA BIOS 8×16 font.
//! - Latin-1 glyphs are procedurally generated by overlaying base
//!   ASCII letters with diacritic marks for the
//!   "letter + accent" codepoints, and by hand-tuned 8×16 bitmaps for
//!   non-letter symbols. The generation lives entirely in
//!   `const fn`s — no runtime cost, no external data file.
//! - Box-drawing glyphs are procedurally generated from a per-
//!   codepoint edge spec `(north, east, south, west)` where each edge
//!   carries one of [`EdgeKind::None`], [`EdgeKind::Light`],
//!   [`EdgeKind::Heavy`], or [`EdgeKind::Double`]. Specials such as
//!   arcs (U+256D..=U+2570), diagonals + X (U+2571..=U+2573), and
//!   half-line endpoints (U+2574..=U+257F) are handled by explicit
//!   case arms.
//!
//! ## Cell size
//!
//! All glyphs use the same 8×16 cell as the existing ASCII font so the
//! resolver can hand back any of them through a single
//! [`crate::session::font::Glyph`] type. The font's cell size is fixed
//! for the lifetime of the font instance; Phase 69c is where wider
//! tables (TTF) will land.

use super::font::Glyph;
