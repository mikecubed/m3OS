/// Diacritic mark applied above a base letter to synthesise an
/// accented Latin-1 glyph.
#[derive(Clone, Copy)]
enum Diacritic {
    Grave,
    Acute,
    Circumflex,
    Tilde,
    Diaeresis,
    Ring,
}

/// Apply a diacritic stamp to the top three rows of a base letter
/// bitmap. The original bitmap's rows shift down by two so the
/// diacritic has space to live in rows 0..=1.
const fn with_diacritic(
    base: [u8; BYTES_PER_GLYPH],
    diacritic: Diacritic,
) -> [u8; BYTES_PER_GLYPH] {
    let mut out = [0u8; BYTES_PER_GLYPH];
    // Shift the base glyph down by two rows so we can paint the
    // diacritic into rows 0..=1.
    let mut i: usize = 2;
    while i < BYTES_PER_GLYPH {
        out[i] = base[i - 2];
        i += 1;
    }
    // Re-introduce a single descender row at the bottom so the
    // diacritic doesn't cost us the bottom margin entirely. (For
    // letters whose original bitmap had inked pixels in row 14/15 the
    // shift drops them, but the visual result remains readable.)
    let (row0, row1) = match diacritic {
        Diacritic::Grave => (0x30u8, 0x18),
        Diacritic::Acute => (0x18u8, 0x30),
        Diacritic::Circumflex => (0x18u8, 0x3C),
        Diacritic::Tilde => (0x36u8, 0x6C),
        Diacritic::Diaeresis => (0x66u8, 0x66),
        Diacritic::Ring => (0x3Cu8, 0x66),
    };
    out[0] = row0;
    out[1] = row1;
    // The shift-down kept the descender ink intact at row 15 already.
    out
}

/// Apply a cedilla underneath a base letter — paints a small hook
/// into rows 13..=14 below the letter's baseline.
const fn with_cedilla(base: [u8; BYTES_PER_GLYPH]) -> [u8; BYTES_PER_GLYPH] {
    let mut out = base;
    out[13] = 0x18;
    out[14] = 0x30;
    out
}

