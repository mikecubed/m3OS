/// First codepoint in the Latin-1 supplement block.
pub const LATIN1_FIRST: u32 = 0x0080;
/// Last codepoint in the Latin-1 supplement block.
pub const LATIN1_LAST: u32 = 0x00FF;
/// First codepoint in the Unicode box-drawing block.
pub const BOX_DRAWING_FIRST: u32 = 0x2500;
/// Last codepoint in the Unicode box-drawing block.
pub const BOX_DRAWING_LAST: u32 = 0x257F;

/// Number of glyphs in each extended table (128 entries each).
const LATIN1_COUNT: usize = (LATIN1_LAST - LATIN1_FIRST + 1) as usize;
const BOX_DRAWING_COUNT: usize = (BOX_DRAWING_LAST - BOX_DRAWING_FIRST + 1) as usize;

/// Bytes per glyph (cell height in pixels, 1 byte per row).
const BYTES_PER_GLYPH: usize = CELL_HEIGHT as usize;

// ---------------------------------------------------------------------------
// Latin-1 supplement bitmaps
// ---------------------------------------------------------------------------

/// 16-byte bitmap of all zeros — used for the C1 control range
/// (U+0080..=U+009F) and the no-break space (U+00A0). Terminals never
/// paint control characters; this matches that contract.
static BLANK: [u8; BYTES_PER_GLYPH] = [0; BYTES_PER_GLYPH];

/// Build the Latin-1 supplement bitmap table at compile time.
const fn build_latin1_bitmaps() -> [[u8; BYTES_PER_GLYPH]; LATIN1_COUNT] {
    let mut out = [[0u8; BYTES_PER_GLYPH]; LATIN1_COUNT];
    let mut i: usize = 0;
    while i < LATIN1_COUNT {
        let codepoint = LATIN1_FIRST + i as u32;
        out[i] = latin1_bitmap_for(codepoint);
        i += 1;
    }
    out
}

