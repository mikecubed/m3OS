def build_codes(bits, vals):
    codes = {}
    code = 0; k = 0
    for length in range(1, 17):
        for _ in range(bits[length-1]):
            codes[vals[k]] = (code, length)
            code += 1; k += 1
        code <<= 1
    return codes

DC = build_codes(DC_BITS, DC_VALS)
AC = build_codes(AC_BITS, AC_VALS)

class BitWriter:
    def __init__(self): self.bits=[]
    def put(self, code, length):
        for i in range(length-1, -1, -1):
            self.bits.append((code >> i) & 1)
    def bytes(self):
        # pad to byte with 1s
        while len(self.bits) % 8: self.bits.append(1)
        out = bytearray()
        for i in range(0, len(self.bits), 8):
            b = 0
            for j in range(8): b = (b<<1) | self.bits[i+j]
            out.append(b)
            if b == 0xFF: out.append(0x00)  # byte stuffing
        return bytes(out)

def category(v):
    return v.bit_length() if v != 0 else 0

def encode_diff(bw, diff):
    cat = category(abs(diff))
    code, length = DC[cat]
    bw.put(code, length)
    if cat:
        mant = diff if diff > 0 else diff + (1<<cat) - 1
        bw.put(mant, cat)

# --- Build entropy stream: 4 blocks, constant values, DC-only + EOB. ---
values = [40, 120, 200, 90]  # distinct -> non-uniform
bw = BitWriter()
prev = 0
for v in values:
    dc = 8 * (v - 128)   # quant table = 1, so quantized DC = raw DC
    encode_diff(bw, dc - prev)
    prev = dc
    ac_code, ac_len = AC[0x00]  # EOB
    bw.put(ac_code, ac_len)
entropy = bw.bytes()

# --- Assemble JPEG. ---
def seg(marker, payload):
    return bytes([0xFF, marker]) + struct.pack(">H", len(payload)+2) + payload

out = bytearray([0xFF, 0xD8])  # SOI
out += seg(0xDB, bytes([0x00]) + bytes([1]*64))                 # DQT id0, all 1s
out += seg(0xC0, bytes([8]) + struct.pack(">HH",16,16) + bytes([1, 1, 0x11, 0]))  # SOF0 1 comp
out += seg(0xC4, bytes([0x00]) + bytes(DC_BITS) + bytes(DC_VALS))  # DHT DC
out += seg(0xC4, bytes([0x10]) + bytes(AC_BITS) + bytes(AC_VALS))  # DHT AC
out += seg(0xDA, bytes([1, 1, 0x00, 0, 63, 0]))                 # SOS
out += entropy
out += bytes([0xFF, 0xD9])  # EOI
