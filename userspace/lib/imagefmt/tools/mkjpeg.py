# Minimal baseline (SOF0) grayscale JPEG encoder — DC-only (each 8x8 block
# a constant value), which any standard baseline decoder reconstructs
# exactly. Produces a 16x16 image (2x2 MCU grid, 1x1 sampling) with four
# distinct block values so the result is non-uniform.
import struct

